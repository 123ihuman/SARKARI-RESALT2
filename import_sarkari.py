import requests, json, sys, argparse
from bs4 import BeautifulSoup
from datetime import datetime

HEADERS = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"}
URL = "https://sarkariresult.com.cm/"

# heading text on source site  ->  your category name
CATEGORY_MAP = [
    ("results",           "Results"),
    ("admit cards",       "Admit Cards"),
    ("latest jobs",       "Latest Jobs"),
    ("answer key",        "Answer Keys"),
    ("documents",         "Documents"),
    ("admission",         "Admission"),
    ("10th/iti jobs",     "10th/ITI Jobs"),
    ("outsourcing",       "Outsourcing Jobs"),
    ("syllabus",          "Syllabus"),
]

def load_html(args):
    if args.file:
        with open(args.file, encoding="utf-8", errors="ignore") as f:
            return f.read()
    r = requests.get(args.url, headers=HEADERS, timeout=25)
    r.raise_for_status()
    return r.text

def extract_items(html):
    soup = BeautifulSoup(html, "html.parser")
    items = []
    # each box = a <ul class="wp-block-latest-posts__list"> preceded by a heading <p class="gb-headline">
    for ul in soup.find_all("ul", class_="wp-block-latest-posts__list"):
        box = ul.find_parent("div", class_="gb-inside-container") or ul.find_parent("div")
        heading = ""
        if box:
            h = box.find("p", class_="gb-headline")
            if h:
                heading = h.get_text(" ", strip=True).lower()
        cat = None
        for key, name in CATEGORY_MAP:
            if key in heading:
                cat = name
                break
        if not cat:
            continue
        for a in ul.find_all("a", href=True):
            title = a.get_text(" ", strip=True)
            href  = a["href"]
            if not title or not href.startswith("http"):
                continue
            items.append({"category": cat, "title": title, "link": href})
    # de-dupe
    seen, out = set(), []
    for it in items:
        k = (it["category"], it["title"].lower())
        if k in seen:
            continue
        seen.add(k)
        out.append(it)
    return out

def make_detail_entry(title, link, today):
    return {
        "title": title,
        "intro": f"{title} — information as published on the source website. Always verify details on the official link.",
        "publication_date": today,
        "start_date": "Refer official notification",
        "last_date": "Refer official notification",
        "exam_date": "Refer official notification",
        "admit_release_date": "Refer official notification",
        "result_date": "Refer official notification",
        "tier_details": "Refer official notification",
        "interview_date": "Not Applicable",
        "fee": ["Refer official website"],
        "age": ["Refer official website"],
        "total": "Refer official website",
        "vacancy": [["Refer official website", "—", "—"]],
        "eligibility": "As per official notification",
        "selection": ["As per official notification"],
        "official": link, "apply": link, "register": link, "login": link,
        "syllabus": link, "pattern": link, "cutoff": link,
        "notification": link, "admit": link, "result": link,
        "faq": [["Where to check the full details?", "Open the official link above."]]
    }

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--url", default=URL)
    p.add_argument("--file", help="parse a saved .html file instead of fetching live")
    args = p.parse_args()

    html = load_html(args)
    items = extract_items(html)
    today = datetime.now().strftime("%d %B %Y")

    # 1) updates.json  (your site's auto-list loader)
    for it in items:
        it["date"] = today
    import os
    os.makedirs("data", exist_ok=True)
    with open("data/updates.json", "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False, indent=2)

    # 2) examdata_add.js  (detail-page data for new items)
    details = {it["title"]: make_detail_entry(it["title"], it["link"], today) for it in items}
    with open("data/examdata_add.js", "w", encoding="utf-8") as f:
        f.write("// Auto-generated by import_sarkari.py — do not edit manually\n")
        f.write("window.examDataAdd = ")
        f.write(json.dumps(details, ensure_ascii=False, indent=2))
        f.write(";\n")

    counts = {}
    for it in items:
        counts[it["category"]] = counts.get(it["category"], 0) + 1
    print(f"✅ Imported {len(items)} entries")
    for c, n in counts.items():
        print(f"   📋 {c}: {n}")
    print("Files written: data/updates.json, data/examdata_add.js")

if __name__ == "__main__":
    main()